/**
 * scripts/build-prefecture-info.js
 *
 * data/jumin-specs/*.js を全件読み込み、
 * js/core/prefecture-info.js を自動生成する。
 *
 * 実行:
 *   node scripts/build-prefecture-info.js
 *
 * 出力:
 *   js/core/prefecture-info.js
 *
 * description.full:
 *   - 超過課税なし県: テンプレート文を自動生成
 *   - 超過課税あり県: 空文字列（手動補完が必要）
 */

import { writeFileSync, readdirSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT      = path.join(__dirname, '..');
const SPECS_DIR = path.join(ROOT, 'data', 'jumin-specs');
const OUTPUT    = path.join(ROOT, 'js', 'core', 'prefecture-info.js');

const JUMIN_DEFAULTS = {
  prefRate:      0.04,
  prefPerCapita: 1_000,
};

// ─── 税名抽出 ─────────────────────────────────────────────────────
// PREF_SOURCE.notes から都道府県独自税の名称を正規表現で取り出す。
// パターン:
//   1. 〇〇で{taxName}+{N}円 (最多)
//   2. 〇〇で{prefPerCapita=N}（{taxName}+{N}円） (岩手・宮城型)
//   3. 〇〇で{taxName}: prefRate=... (神奈川型)
function extractTaxName(notes) {
  if (!notes) return null;
  if (notes.includes('超過課税なし') || notes.includes('超過なし')) return null;

  // パターン 1: "で{taxName}+数字"
  let m = notes.match(/で([^\s（(+][^+\n]+?)\+\d/);
  if (m) {
    const name = m[1].trim().replace(/\s+/g, '');
    if (!name.startsWith('均等割') && !name.startsWith('所得割') && !name.startsWith('prefPerCapita')) {
      return name;
    }
  }

  // パターン 2: "（{taxName}+数字円）" — prefPerCapita=N（{taxName}+N円）形式
  // ※ 1,000円のようにカンマを含む数値に対応するため [\d,]+ を使用
  m = notes.match(/（([^）+]+)\+[\d,]+円/);
  if (m) return m[1].trim().replace(/\s+/g, '');

  // パターン 3: "で{taxName}:" — 神奈川型
  m = notes.match(/で([^\s：:（(][^：:\n（(]+?)[：:]/);
  if (m) {
    const name = m[1].trim().replace(/\s+/g, '');
    if (!name.startsWith('均等割') && !name.startsWith('所得割')) return name;
  }

  return null;
}

// ─── 超過額の計算 ─────────────────────────────────────────────────
function calcSurcharge(prefRate, prefPerCapita) {
  const perCapita = Math.round(prefPerCapita - JUMIN_DEFAULTS.prefPerCapita);
  // 浮動小数点誤差を避けるため 1e7 倍で比較
  const rateRaw   = Math.round((prefRate - JUMIN_DEFAULTS.prefRate) * 1_000_000) / 1_000_000;

  if (perCapita === 0 && rateRaw === 0) return null;

  return {
    ...(perCapita !== 0 ? { perCapita } : {}),
    ...(rateRaw   !== 0 ? { rate: rateRaw } : {}),
  };
}

// ─── 短い説明文の自動生成 ──────────────────────────────────────────
function buildShortDesc(surcharge, taxName) {
  if (!surcharge) return '超過課税なし（標準税率）';

  const parts = [];

  if (surcharge.perCapita) {
    const yen  = surcharge.perCapita.toLocaleString('ja-JP');
    const tag  = taxName ? `（${taxName}）` : '';
    parts.push(`均等割+${yen}円${tag}`);
  }
  if (surcharge.rate) {
    const pct  = (surcharge.rate * 100).toFixed(3).replace(/\.?0+$/, '');
    const tag  = taxName && !parts.length ? `（${taxName}）` : '';
    parts.push(`所得割+${pct}%${tag}`);
  }

  return parts.join('・');
}

// ─── 長い説明文（超過課税なし県は自動生成）──────────────────────────
function buildFullDesc(prefName, surcharge, taxName) {
  if (!surcharge) {
    // 東京都は「都民税」、それ以外は「県民税」
    const taxType = prefName === '東京都' ? '都民税' : '県民税';
    return `${prefName}では個人${taxType}の超過課税はありません。地方税法の標準税率（所得割4%、均等割1,000円）が適用されています。`;
  }
  // 超過課税あり → 手動補完が必要
  return '';
}

// ─── メイン ───────────────────────────────────────────────────────
const specFiles = readdirSync(SPECS_DIR)
  .filter(f => f.endsWith('.js') && f !== '_template.js')
  .sort();

const info   = {};
const errors = [];

for (const file of specFiles) {
  const slug    = file.replace('.js', '');
  const fileUrl = `file://${SPECS_DIR}/${file}`;

  try {
    const spec = await import(fileUrl);

    const prefRate      = spec.PREF_DEFAULTS?.prefRate      ?? JUMIN_DEFAULTS.prefRate;
    const prefPerCapita = spec.PREF_DEFAULTS?.prefPerCapita ?? JUMIN_DEFAULTS.prefPerCapita;
    const sourceUrl     = spec.PREF_SOURCE?.url  ?? null;
    const notes         = spec.PREF_SOURCE?.notes ?? '';

    const surcharge = calcSurcharge(prefRate, prefPerCapita);
    const taxName   = extractTaxName(notes);

    info[slug] = {
      name:         spec.PREF_NAME,
      prefRate,
      prefPerCapita,
      surcharge,
      taxName:      taxName ?? null,
      sourceUrl,
      description: {
        short: buildShortDesc(surcharge, taxName),
        full:  buildFullDesc(spec.PREF_NAME, surcharge, taxName),
      },
    };
  } catch (e) {
    errors.push(`${file}: ${e.message}`);
  }
}

if (errors.length) {
  console.error('❌ エラー:');
  errors.forEach(e => console.error('  ' + e));
}

// ─── 出力 ──────────────────────────────────────────────────────────
const surchargeCount = Object.values(info).filter(v => v.surcharge).length;
const noSurchargeCount = Object.values(info).filter(v => !v.surcharge).length;

const output = `/**
 * 都道府県別 住民税情報
 *
 * AUTO-GENERATED by scripts/build-prefecture-info.js
 * 元データ: data/jumin-specs/*.js
 * 生成日時: ${new Date().toISOString().slice(0, 10)}
 *
 * 超過課税あり: ${surchargeCount}都道府県
 * 超過課税なし: ${noSurchargeCount}都道府県
 *
 * description.full（超過課税あり県）は手動補完が必要です。
 * 再生成: node scripts/build-prefecture-info.js
 */

const PREFECTURE_INFO = ${JSON.stringify(info, null, 2)};

// Node.js 環境向け（js/core/package.json で type:commonjs のため CJS で書き出す）
if (typeof module !== 'undefined') module.exports = { PREFECTURE_INFO };
`;

writeFileSync(OUTPUT, output, 'utf-8');

// ─── サマリー ──────────────────────────────────────────────────────
console.log(`\n✅ prefecture-info.js を生成しました`);
console.log(`   ${Object.keys(info).length}都道府県 | 超過課税あり: ${surchargeCount} | なし: ${noSurchargeCount}`);
console.log(`   出力: js/core/prefecture-info.js`);

if (surchargeCount > 0) {
  console.log(`\n📝 description.full の手動補完が必要な都道府県（${surchargeCount}件）:`);
  Object.entries(info)
    .filter(([, v]) => v.surcharge)
    .forEach(([slug, v]) => {
      console.log(`   ${v.name.padEnd(6)} ${v.description.short}`);
    });
}
