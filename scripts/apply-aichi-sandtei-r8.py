registry = json.load(open(os.path.join(ROOT, "registry/index.json")))
by_name = {m["cityName"]: m for m in registry["municipalities"] if m["prefecture"] == "愛知県"}

updated, skipped = 0, []
for row in ROWS:
    name = row[0]
    m = by_name.get(name)
    if not m:
        skipped.append(f"{name}: registryに無し"); continue
    path = os.path.join(ROOT, "data/municipalities", m["citySlug"], "kokuho-2026.json")
    if not os.path.exists(path):
        skipped.append(f"{name}: JSONなし"); continue
    d = json.load(open(path))
    if d.get("meta", {}).get("lifecycle", {}).get("r8Stage") != "standard_r8":
        skipped.append(f"{name}: standard_r8でない({d.get('meta',{}).get('status')})"); continue

